  function translate(value) {
    const match = String(value).match(/^(\s*)([\s\S]*?)(\s*)$/);
    return `${match[1]}${phrase(match[2])}${match[3]}`;
  }
  function walk(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (!originalText.has(node)) originalText.set(node, node.nodeValue);
      const original = originalText.get(node);
      const next = language === 'gu' ? translate(original) : original;
      if (node.nodeValue !== next) node.nodeValue = next;
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_NODE) return;
    if (node.nodeType === Node.ELEMENT_NODE) {
      if (node.matches('[data-language-toggle]')) return;
      if (['SCRIPT', 'STYLE'].includes(node.tagName)) return;
      let attrs = originalAttrs.get(node);
      if (!attrs) {
        attrs = {};
        for (const name of ['placeholder', 'aria-label', 'title']) if (node.hasAttribute(name)) attrs[name] = node.getAttribute(name);
        originalAttrs.set(node, attrs);
      }
      for (const [name, original] of Object.entries(attrs)) node.setAttribute(name, language === 'gu' ? translate(original) : original);
    }
    for (const child of node.childNodes) walk(child);
  }
